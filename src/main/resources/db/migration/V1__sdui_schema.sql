-- =============================================================================
-- SDUI storage — 3 blob artefacts (style / tree / script) + frozen releases (H2 2.x)
-- Design: packages/sdui/DESAIN-SISTEM-SDUI.md
--
-- H2 notes (vs the PostgreSQL design):
--   * JSON is stored as CLOB text; shape is validated by the application.
--   * text[] columns are JSON arrays in CLOB.
--   * Immutability triggers and the assembly function are Java classes
--     (package com.fajekrina.universal.db), so the view stays the single
--     place where payload assembly is defined.
-- =============================================================================

CREATE TABLE sdui_merchant (
  merchant_id       VARCHAR(64)  PRIMARY KEY CHECK (REGEXP_LIKE(merchant_id, '^[a-z0-9_]{3,64}$')),
  name              VARCHAR(200) NOT NULL,
  status            VARCHAR(16)  DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'SUSPENDED')),
  default_style_key VARCHAR(64),
  created_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE sdui_bounds (
  bounds_version        INT PRIMARY KEY CHECK (bounds_version > 0),
  max_depth             INT NOT NULL CHECK (max_depth > 0),
  max_nodes             INT NOT NULL CHECK (max_nodes > 0),
  max_string_length     INT NOT NULL CHECK (max_string_length > 0),
  max_props             INT NOT NULL CHECK (max_props > 0),
  max_children          INT NOT NULL CHECK (max_children > 0),
  max_array_items       INT NOT NULL CHECK (max_array_items > 0),
  max_identifier_length INT NOT NULL CHECK (max_identifier_length > 0),
  max_chain_depth       INT NOT NULL CHECK (max_chain_depth > 0),
  created_at            TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE sdui_policy (
  merchant_id     VARCHAR(64) NOT NULL REFERENCES sdui_merchant (merchant_id),
  policy_version  INT         NOT NULL CHECK (policy_version > 0),
  allowed_domains CLOB        DEFAULT '[]' NOT NULL,   -- JSON array of strings
  allowed_events  CLOB        DEFAULT '[]' NOT NULL,   -- JSON array of strings
  bounds_version  INT         NOT NULL REFERENCES sdui_bounds (bounds_version),
  created_by      VARCHAR(128) NOT NULL,
  created_at      TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PRIMARY KEY (merchant_id, policy_version)
);

CREATE TABLE sdui_component_type (
  component_type       VARCHAR(32) PRIMARY KEY CHECK (REGEXP_LIKE(component_type, '^[A-Z][A-Za-z0-9]{1,31}$')),
  category             VARCHAR(16) NOT NULL CHECK (category IN ('layout', 'content', 'form', 'navigation', 'feedback')),
  accepts_children     BOOLEAN     NOT NULL,
  props_schema         CLOB        DEFAULT '{}' NOT NULL,
  default_props        CLOB        DEFAULT '{}' NOT NULL,
  allowed_behaviors    CLOB        DEFAULT '[]' NOT NULL, -- JSON array
  since_schema_version VARCHAR(8)  DEFAULT '1.0' NOT NULL,
  enabled              BOOLEAN     DEFAULT TRUE NOT NULL,
  updated_at           TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE sdui_behavior (
  behavior        VARCHAR(32)  PRIMARY KEY CHECK (REGEXP_LIKE(behavior, '^[a-z][A-Za-z]{1,31}$')),
  required_fields CLOB         DEFAULT '[]' NOT NULL, -- JSON array
  policy_check    VARCHAR(8)   DEFAULT 'none' NOT NULL CHECK (policy_check IN ('domain', 'event', 'none')),
  description     VARCHAR(256) NOT NULL,
  enabled         BOOLEAN      DEFAULT TRUE NOT NULL
);

CREATE TABLE sdui_page (
  page_id           VARCHAR(160) PRIMARY KEY,
  merchant_id       VARCHAR(64)  NOT NULL REFERENCES sdui_merchant (merchant_id),
  page_key          VARCHAR(64)  NOT NULL CHECK (REGEXP_LIKE(page_key, '^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$')),
  status            VARCHAR(16)  DEFAULT 'DRAFT' NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
  draft_tree_id     BIGINT,
  draft_script_id   BIGINT,
  draft_style_id    BIGINT,
  active_release_id BIGINT,
  lock_version      INT          DEFAULT 0 NOT NULL,
  created_by        VARCHAR(128) NOT NULL,
  created_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  archived_at       TIMESTAMP WITH TIME ZONE,
  CONSTRAINT uq_page_key UNIQUE (merchant_id, page_key),
  CONSTRAINT uq_page_merchant UNIQUE (page_id, merchant_id)
);

-- Style artefact: owned by the merchant, shared by many pages
CREATE TABLE sdui_style (
  style_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id  VARCHAR(64)  NOT NULL REFERENCES sdui_merchant (merchant_id),
  style_key    VARCHAR(64)  NOT NULL CHECK (REGEXP_LIKE(style_key, '^[a-z0-9][a-z0-9-]{0,63}$')),
  version      INT          NOT NULL CHECK (version > 0),
  body         CLOB         NOT NULL,   -- {"tokens":{category:{name:value}}, "shared":{name:{css}}}
  content_hash VARCHAR(64)  NOT NULL,   -- sha256 hex of canonical body
  token_count  INT          NOT NULL,
  created_by   VARCHAR(128) NOT NULL,
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  note         VARCHAR(512),
  CONSTRAINT uq_style_version UNIQUE (merchant_id, style_key, version),
  CONSTRAINT uq_style_hash UNIQUE (merchant_id, style_key, content_hash),
  CONSTRAINT uq_style_merchant UNIQUE (style_id, merchant_id)
);

-- Tree artefact: owned by the page; nested children only (parentId/order derived on assembly)
CREATE TABLE sdui_tree (
  tree_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id        VARCHAR(160) NOT NULL,
  merchant_id    VARCHAR(64)  NOT NULL,
  version        INT          NOT NULL CHECK (version > 0),
  body           CLOB         NOT NULL,   -- {"schemaVersion","layout":{type,title,subtitle},"nodes":[…]}
  content_hash   VARCHAR(64)  NOT NULL,
  schema_version VARCHAR(8)   NOT NULL CHECK (REGEXP_LIKE(schema_version, '^[0-9]+\.[0-9]+$')),
  node_count     INT          NOT NULL,
  max_depth      INT          NOT NULL,
  created_by     VARCHAR(128) NOT NULL,
  created_at     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  note           VARCHAR(512),
  CONSTRAINT fk_tree_page FOREIGN KEY (page_id, merchant_id) REFERENCES sdui_page (page_id, merchant_id),
  CONSTRAINT uq_tree_version UNIQUE (page_id, version),
  CONSTRAINT uq_tree_hash UNIQUE (page_id, content_hash),
  CONSTRAINT uq_tree_page UNIQUE (tree_id, page_id)
);

-- Script artefact: owned by the page; named declarative actions
CREATE TABLE sdui_script (
  script_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id      VARCHAR(160) NOT NULL,
  merchant_id  VARCHAR(64)  NOT NULL,
  version      INT          NOT NULL CHECK (version > 0),
  body         CLOB         NOT NULL,   -- {"actions":{name:{behavior,…}}, "events":[…]}
  content_hash VARCHAR(64)  NOT NULL,
  action_count INT          NOT NULL,
  created_by   VARCHAR(128) NOT NULL,
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_script_page FOREIGN KEY (page_id, merchant_id) REFERENCES sdui_page (page_id, merchant_id),
  CONSTRAINT uq_script_version UNIQUE (page_id, version),
  CONSTRAINT uq_script_hash UNIQUE (page_id, content_hash),
  CONSTRAINT uq_script_page UNIQUE (script_id, page_id)
);

CREATE TABLE sdui_signing_key (
  key_id      VARCHAR(64)  PRIMARY KEY,
  merchant_id VARCHAR(64)  REFERENCES sdui_merchant (merchant_id),  -- NULL = global key
  algorithm   VARCHAR(16)  DEFAULT 'Ed25519' NOT NULL CHECK (algorithm = 'Ed25519'),
  public_key  VARCHAR(128) NOT NULL,   -- raw 32-byte key, base64 (private key stays in config)
  status      VARCHAR(16)  DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'RETIRED', 'REVOKED')),
  created_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  retired_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE sdui_release (
  release_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id        VARCHAR(160) NOT NULL,
  merchant_id    VARCHAR(64)  NOT NULL,
  sequence       INT          NOT NULL CHECK (sequence > 0),
  tree_id        BIGINT       NOT NULL,
  style_id       BIGINT,
  script_id      BIGINT,
  policy_version INT          NOT NULL,
  payload        CLOB,                 -- frozen view output (filled once at publish)
  content_hash   VARCHAR(64),          -- sha256 hex of payload bytes = ETag
  signature      VARCHAR(256),         -- Ed25519 over payload bytes, base64 (filled once)
  signing_key_id VARCHAR(64) REFERENCES sdui_signing_key (key_id),
  rollback_of    BIGINT REFERENCES sdui_release (release_id),
  published_by   VARCHAR(128) NOT NULL,
  published_at   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  note           VARCHAR(512),
  CONSTRAINT fk_release_page   FOREIGN KEY (page_id, merchant_id)        REFERENCES sdui_page (page_id, merchant_id),
  CONSTRAINT fk_release_tree   FOREIGN KEY (tree_id, page_id)            REFERENCES sdui_tree (tree_id, page_id),
  CONSTRAINT fk_release_script FOREIGN KEY (script_id, page_id)          REFERENCES sdui_script (script_id, page_id),
  CONSTRAINT fk_release_style  FOREIGN KEY (style_id, merchant_id)       REFERENCES sdui_style (style_id, merchant_id),
  CONSTRAINT fk_release_policy FOREIGN KEY (merchant_id, policy_version) REFERENCES sdui_policy (merchant_id, policy_version),
  CONSTRAINT uq_release_seq  UNIQUE (page_id, sequence),
  CONSTRAINT uq_release_page UNIQUE (release_id, page_id)
);
CREATE INDEX ix_release_page_seq ON sdui_release (page_id, sequence DESC);

CREATE TABLE sdui_audit_log (
  audit_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id VARCHAR(64)  NOT NULL REFERENCES sdui_merchant (merchant_id),
  page_id     VARCHAR(160),
  event       VARCHAR(16)  NOT NULL CHECK (event IN ('SAVE_DRAFT', 'PUBLISH', 'ROLLBACK', 'ARCHIVE', 'SIGN', 'STYLE_SAVE', 'POLICY_SAVE')),
  release_id  BIGINT REFERENCES sdui_release (release_id),
  actor       VARCHAR(128) NOT NULL,
  request_id  VARCHAR(64),
  detail      CLOB DEFAULT '{}' NOT NULL,
  at          TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX ix_audit_page_at ON sdui_audit_log (page_id, at DESC);

-- page → artefact / release pointers (circular, so added after the tables exist)
ALTER TABLE sdui_page ADD CONSTRAINT fk_page_tree    FOREIGN KEY (draft_tree_id, page_id)       REFERENCES sdui_tree (tree_id, page_id);
ALTER TABLE sdui_page ADD CONSTRAINT fk_page_script  FOREIGN KEY (draft_script_id, page_id)     REFERENCES sdui_script (script_id, page_id);
ALTER TABLE sdui_page ADD CONSTRAINT fk_page_style   FOREIGN KEY (draft_style_id, merchant_id)  REFERENCES sdui_style (style_id, merchant_id);
ALTER TABLE sdui_page ADD CONSTRAINT fk_page_release FOREIGN KEY (active_release_id, page_id)   REFERENCES sdui_release (release_id, page_id);

-- Immutability (enforced by the database, not by convention)
CREATE TRIGGER trg_bounds_immutable BEFORE UPDATE ON sdui_bounds FOR EACH ROW CALL 'com.fajekrina.universal.db.ImmutableRowTrigger';
CREATE TRIGGER trg_policy_immutable BEFORE UPDATE ON sdui_policy FOR EACH ROW CALL 'com.fajekrina.universal.db.ImmutableRowTrigger';
CREATE TRIGGER trg_style_immutable  BEFORE UPDATE ON sdui_style  FOR EACH ROW CALL 'com.fajekrina.universal.db.ImmutableRowTrigger';
CREATE TRIGGER trg_tree_immutable   BEFORE UPDATE ON sdui_tree   FOR EACH ROW CALL 'com.fajekrina.universal.db.ImmutableRowTrigger';
CREATE TRIGGER trg_script_immutable BEFORE UPDATE ON sdui_script FOR EACH ROW CALL 'com.fajekrina.universal.db.ImmutableRowTrigger';
-- releases: payload/content_hash, then signature/signing_key_id, may each be filled exactly once
CREATE TRIGGER trg_release_fill_once BEFORE UPDATE ON sdui_release FOR EACH ROW CALL 'com.fajekrina.universal.db.ReleaseGuardTrigger';
CREATE TRIGGER trg_release_no_delete BEFORE DELETE ON sdui_release FOR EACH ROW CALL 'com.fajekrina.universal.db.ImmutableRowTrigger';

-- =============================================================================
-- VIEW: assembled payload, one row per release.
-- SDUI_ASSEMBLE flattens the nested tree (pre-order → parentId/order), merges
-- style (shared < token < inline) and resolves actionRef → props.action.
-- Library presets are NOT applied here (they stay in the client core).
-- =============================================================================
CREATE ALIAS SDUI_ASSEMBLE   FOR 'com.fajekrina.universal.db.SduiDbFunctions.assemble';
CREATE ALIAS SDUI_UNRESOLVED FOR 'com.fajekrina.universal.db.SduiDbFunctions.unresolved';
CREATE ALIAS SDUI_NODE_COUNT FOR 'com.fajekrina.universal.db.SduiDbFunctions.nodeCount';

CREATE VIEW v_sdui_release_payload AS
SELECT r.release_id,
       r.merchant_id,
       p.page_key,
       r.sequence,
       CASE WHEN p.active_release_id = r.release_id THEN TRUE ELSE FALSE END AS is_active,
       r.published_at,
       SDUI_NODE_COUNT(r.release_id) AS node_count,
       SDUI_UNRESOLVED(r.release_id) AS unresolved_refs,
       SDUI_ASSEMBLE(r.release_id)   AS payload
FROM sdui_release r
JOIN sdui_page p ON p.page_id = r.page_id;
