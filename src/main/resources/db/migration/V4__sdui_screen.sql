-- =============================================================================
-- Spec screens: payloads in the @fajekrina/sdui spec format ({schemaVersion, screen})
-- stored as ONE document per screen (the client owns layout and style), validated
-- against the bundled spec schema, released immutably, and listed in a manifest.
-- =============================================================================

CREATE TABLE sdui_screen (
  merchant_id       VARCHAR(64)  NOT NULL REFERENCES sdui_merchant (merchant_id),
  screen_key        VARCHAR(128) NOT NULL CHECK (REGEXP_LIKE(screen_key, '^[A-Za-z][A-Za-z0-9_]*$')),
  status            VARCHAR(16)  DEFAULT 'DRAFT' NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
  draft             CLOB         NOT NULL,   -- canonical spec payload JSON
  draft_hash        VARCHAR(64)  NOT NULL,   -- sha256 hex of draft
  active_release_id BIGINT,
  created_by        VARCHAR(128) NOT NULL,
  created_time      TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_by        VARCHAR(128) NOT NULL,
  updated_time      TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  version           INT          DEFAULT 0 NOT NULL,
  PRIMARY KEY (merchant_id, screen_key)
);

CREATE TABLE sdui_screen_release (
  release_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id    VARCHAR(64)  NOT NULL,
  screen_key     VARCHAR(128) NOT NULL,
  sequence       INT          NOT NULL CHECK (sequence > 0),
  payload        CLOB         NOT NULL,   -- frozen bytes served to clients
  content_hash   VARCHAR(64)  NOT NULL,   -- sha256 hex of payload = ETag
  signature      VARCHAR(256),            -- Ed25519 over payload bytes, base64 (when signing is on)
  signing_key_id VARCHAR(64) REFERENCES sdui_signing_key (key_id),
  created_by     VARCHAR(128) NOT NULL,
  created_time   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_screen_release_screen FOREIGN KEY (merchant_id, screen_key) REFERENCES sdui_screen (merchant_id, screen_key),
  CONSTRAINT uq_screen_release_seq UNIQUE (merchant_id, screen_key, sequence)
);
CREATE INDEX ix_screen_release_merchant ON sdui_screen_release (merchant_id, release_id DESC);

ALTER TABLE sdui_screen ADD CONSTRAINT fk_screen_active_release FOREIGN KEY (active_release_id) REFERENCES sdui_screen_release (release_id);

-- releases are written once, complete (signature included), and never change or disappear
CREATE TRIGGER trg_screen_release_immutable BEFORE UPDATE ON sdui_screen_release FOR EACH ROW CALL 'com.fajekrina.universal.db.ImmutableRowTrigger';
CREATE TRIGGER trg_screen_release_no_delete BEFORE DELETE ON sdui_screen_release FOR EACH ROW CALL 'com.fajekrina.universal.db.ImmutableRowTrigger';
